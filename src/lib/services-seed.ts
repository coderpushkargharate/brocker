/** A believable 5→1 star breakdown for a given average and count. */
export function ratingFor(avg: number, count: number): RatingInfo {
  if (!count) return { rating: 0, reviewCount: 0, ratingDist: [0, 0, 0, 0, 0] };
  const c2 = Math.round(count * 0.01);
  const c3 = Math.round(count * 0.04);
  const rest = count - c2 - c3;
  const target = Math.round(avg * count) - 2 * c2 - 3 * c3;
  const c5 = Math.max(0, Math.min(rest, target - 4 * rest));
  const dist = [c5, rest - c5, c3, c2, 0];
  return { ...ratingFromDist(dist) };
}

export function ratingFromDist(dist: number[]): RatingInfo {
  const count = dist.reduce((s, n) => s + n, 0);
  const sum = dist.reduce((s, n, i) => s + n * (5 - i), 0);
  return { rating: count ? Math.round((sum / count) * 10) / 10 : 0, reviewCount: count, ratingDist: dist };
}

